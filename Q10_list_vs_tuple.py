#list vs tuple
#List: A list is a collection of items that can be changed, added, or removed after it is created.
#Tuple: A tuple is a collection of items that cannot be changed, added, or removed after it is created.

my_list = [1, 2, 3]
my_tuple = (1, 2, 3)

print("List:", my_list)
print("Tuple:", my_tuple)

print("List can be changed")
print("Tuple cannot be changed")